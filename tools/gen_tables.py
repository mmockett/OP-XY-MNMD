#!/usr/bin/env python3
"""Writes lib/md_tables.hpp: the fixed-point tables every machine shares.

The OP-XY's Blackfin has no floating point, so anything transcendental is a
table computed here, once, in double precision. Run it after changing a table,
then tools/make_engine.py to copy the library into each machine.
"""
import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "lib" / "md_tables.hpp"
Q31 = 2147483647
FS = 44100.0


def q31(x):
    return max(-Q31, min(Q31, round(x * 2147483648.0)))


def table(name, kind, values, per_line=8):
    n = len(values)
    lines = [f"template <int> struct {name}_data {{ static const {kind} values[{n}]; }};",
             f"template <int N> const {kind} {name}_data<N>::values[{n}] = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    lines.append(f"static const {kind} (&{name})[{n}] = {name}_data<0>::values;")
    return "\n".join(lines)


# One sine cycle, 1024 steps plus a guard entry for interpolation.
sine = [q31(math.sin(2 * math.pi * i / 1024)) for i in range(1025)]

# 2^(i/256) for one octave, Q30 (1.0 .. 2.0), plus a guard entry.
exp2 = [round(2 ** (i / 256) * (1 << 30)) for i in range(257)]
exp2[-1] = min(exp2[-1], Q31)

# Per-sample decay multipliers for a fall of 60 dB in T samples, indexed by
# log2(T) from 4 (16 samples) to 20 (about 24 s) in 1/16 octave steps.
DECAY_LOW, DECAY_OCTAVES = 4, 16
decay = []
for i in range(DECAY_OCTAVES * 16 + 1):
    t = 2 ** (DECAY_LOW + i / 16)
    decay.append(q31(math.exp(math.log(0.001) / t)))

# Chamberlin state-variable frequency coefficient f/2 = sin(pi fc / fs), Q31,
# indexed by log2(fc / 20 Hz) over 9 octaves (20 Hz .. 10.24 kHz), 1/32 octave.
SVF_OCTAVES = 9
svf = []
for i in range(SVF_OCTAVES * 32 + 1):
    fc = 20 * 2 ** (i / 32)
    svf.append(q31(math.sin(math.pi * min(fc, FS / 4) / FS)))

# The phase increment half a semitone below each MIDI note, at 44.1 kHz: a kit
# finds the played key from a note's pitch with these (lib/md_kit.hpp).
def increment(note):
    return 440 * 2 ** ((note - 69) / 12) / FS * 2 ** 32
note_edge = [0] + [round(increment(n - 0.5)) for n in range(1, 128)]

# e^-x for x = i/32 over 0 .. 8, Q31: for the screens' curves.
expneg = [q31(math.exp(-i / 32)) for i in range(257)]

text = f"""#pragma once
// Generated by tools/gen_tables.py; edit the generator, not this file.
#include <opxy/types.hpp>

namespace md {{
using opxy::i32;
using opxy::u32;

// Each table is a template's static member, which the linker keeps once for
// every translation unit and engine that includes this header (a static array
// would be copied into each).

// Sine, Q31, 1024 steps per cycle and a guard entry.
{table("sine_table", "i32", sine)}

// 2^(i/256), Q30, one octave and a guard entry.
{table("exp2_table", "i32", exp2)}

// Per-sample multiplier falling 60 dB over 2^(4 + i/16) samples, Q31.
const i32 decay_low_octave = {DECAY_LOW};
const i32 decay_steps = {DECAY_OCTAVES * 16};
{table("decay_table", "i32", decay)}

// The phase increment half a semitone below each MIDI note (0 for note 0).
{table("note_edge_table", "u32", [f"{v}u" for v in note_edge])}

// e^-(i/32), Q31, x from 0 to 8.
{table("expneg_table", "i32", expneg)}

// sin(pi fc / fs) for fc = 20 Hz * 2^(i/32), Q31: half the SVF frequency coefficient.
const i32 svf_steps = {SVF_OCTAVES * 32};
{table("svf_table", "i32", svf)}
}}
"""
OUT.write_text(text)
print(f"wrote {OUT}")
