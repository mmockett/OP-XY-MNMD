export const ADVANCE = 5.0;   // grid units from one letter to the next: 0.56 of the font size, as the design measures

// The polylines of `text` at size `px` (the design's font size), from its
// top-left (x, y), as the design's labels are placed; upper case is drawn lower.
export function strokes(text, x, y, px = 9) {
  const k = px / 9;   // grid unit in pixels
  const out = [];
  let pen = 0;
  for (const ch of text.toLowerCase()) {
    if (ch === ' ') { pen += ADVANCE * 0.7; continue; }
    const glyph = G[ch];
    if (!glyph) { pen += ADVANCE; continue; }   // an unknown character leaves a space
    for (const line of glyph) out.push(line.map(([gx, gy]) => [x + (pen + gx) * k, y + 1.5 * k + gy * k]));
    pen += ADVANCE;
  }
  return out;
}

export function width(text, px = 9) { return text.length * ADVANCE * px / 9; }
